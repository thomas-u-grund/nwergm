# Writes cscripts/test_nwergm_curveddeg.do: the curved (fixed = FALSE) directed degree terms gwodegree and gwidegree of nwergm
# (options gwodegreefree, gwidegreefree) against R ergm 4.12.0: MPLE coefficients/SE and MCMLE within Monte Carlo noise (two seeds)
# on a random directed network with heterogeneous degrees.  usage (from the repository root): Rscript dev/gen_test_curveddeg.R
suppressMessages({library(ergm); library(network)})
set.seed(7)
n <- 30; ao <- rgamma(n, 2)/2; ai <- rgamma(n, 2)/2; D <- matrix(0, n, n)
for (i in 1:n) for (j in 1:n) if (i != j) D[i,j] <- rbinom(1, 1, min(.9, .1*ao[i]*ai[j]))
nw <- network(D, directed = TRUE)
fmt <- function(v) paste(formatC(v, digits=15, format="g"), collapse=" ")
out <- character(); w <- function(...) out <<- c(out, sprintf(...))
w("cscript"); w("")
w("capture adopath ++ \".\""); w("capture adopath ++ \"lib\"")
w("* The core package nwcommands is found through the environment variable NWCORE (path of the core checkout).")
w("local nwcore : env NWCORE")
w("if `\"`nwcore'\"' == \"\" {"); w("	di as error \"set the environment variable NWCORE to the directory of the nwcommands (core) package\""); w("	exit 198"); w("}")
w("adopath ++ `\"`nwcore'\"'"); w("adopath ++ `\"`c(pwd)'\"'")
w("quietly do `\"`nwcore'/unw_core.do\"'"); w("do unw_ergm.do")
w("capture adopath ++ \"lib/plugins/macos\""); w("capture adopath ++ \"lib/plugins/unix\""); w("capture adopath ++ \"lib/plugins/windows\"")
w("")
w("* Certifies gwodegreefree() and gwidegreefree() against R ergm 4.12.0 (gwodegree, gwidegree with fixed = FALSE); dev/gen_test_curveddeg.R")
w("")
e <- which(D == 1, arr.ind = TRUE)
w("matrix __A = J(%d, %d, 0)", n, n)
w("local el `\"%s\"'", paste(as.vector(t(e)), collapse=" "))
w("local k : word count `el'"); w("forvalues t = 1(2)`k' {"); w("	local i : word `t' of `el'"); w("	local j : word `=`t'+1' of `el'"); w("	matrix __A[`i', `j'] = 1"); w("}")
w("nwset, mat(__A) directed name(dd) nooutput"); w("")
for (tm in c("gwodegree", "gwidegree")) {
  f <- as.formula(paste("nw ~ edges +", tm))
  r <- suppressWarnings(suppressMessages(ergm(f, estimate="MPLE")))
  m <- suppressWarnings(suppressMessages(ergm(f, control=control.ergm(seed=3, MCMC.samplesize=6000, MCMC.interval=500, MCMC.burnin=20000))))
  opt <- paste0(tm, "free")
  cat(tm, round(coef(r), 4), "|", round(coef(m), 4), round(sqrt(diag(vcov(m))), 3), "\n")
  w("qui nwergm dd, edges %s(0.5) method(mple)", opt)
  w("matrix bb = e(b)"); w("matrix VV = e(V)")
  cr <- coef(r); sr <- sqrt(diag(vcov(r)))
  w("local __cf \"%s\"", fmt(cr)); w("local __sf \"%s\"", fmt(sr))
  w("forvalues j = 1/3 {")
  w("	local e : word `j' of `__cf'"); w("	local s : word `j' of `__sf'")
  w("	if !(abs(el(bb,1,`j') - (`e')) < 1e-3 * max(1, abs(`e'))) exit 9"); w("	if !(abs(sqrt(el(VV,`j',`j')) - (`s')) < 1e-3 * max(1, `s')) exit 9"); w("}")
  w("di \"PASS %s: MPLE equal to R\"", opt)
  if (coef(r)[3] < 0.05) next   # the pseudolikelihood fit is at the boundary of the decay: no starting point for the maximum likelihood
  cm <- coef(m); sm <- sqrt(diag(vcov(m)))
  w("foreach sd in 101 202 {"); w("	set seed `sd'")
  w("	qui nwergm dd, edges %s(0.5) method(mcmle) mcmcsamplesize(2000) mcmcinterval(200) mcmcburnin(5000) mcmleiterations(25) nologlik", opt)
  w("	matrix bb = e(b)")
  w("	local __cf \"%s\"", fmt(cm)); w("	local __sf \"%s\"", fmt(sm))
  w("	forvalues j = 1/3 {"); w("		local e : word `j' of `__cf'"); w("		local s : word `j' of `__sf'")
  w("		if !(abs(el(bb,1,`j') - (`e')) < 3.5 * `s') exit 9"); w("	}"); w("}")
  w("di \"PASS %s: MCMLE within Monte Carlo noise of R for two seeds\"", opt)
}
w("di \"test_nwergm_curveddeg: ALL OK\"")
writeLines(out, "cscripts/test_nwergm_curveddeg.do")
