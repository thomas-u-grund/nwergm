# Writes cscripts/test_nwergm_bipcurved.do: the curved (fixed = FALSE) bipartite terms gwb1degree, gwb2degree, gwb1dsp, gwb2dsp of nwergm
# (options bgwdegreefree1/2, bgwdspfree1/2) against R ergm 4.12.0 on random two-mode networks:
#   (a) MPLE coefficients (edges, weight, decay) and standard errors, ergm(estimate = "MPLE")
#   (b) MCMLE coefficients within Monte Carlo noise of an R fit with a long chain, for two seeds
# usage (from the repository root): Rscript dev/gen_test_bipcurved.R
suppressMessages({library(ergm); library(network)})

mk_block <- function(seed, pin, n1range = 20:35, n2range = 25:45, K = 3) {
  set.seed(seed * 77)
  n1 <- sample(n1range, 1); n2 <- sample(n2range, 1)
  g1 <- sample(1:K, n1, TRUE); g2 <- sample(1:K, n2, TRUE)
  B <- matrix(0, n1, n2)
  for (i in 1:n1) for (j in 1:n2) B[i,j] <- rbinom(1, 1, ifelse(g1[i] == g2[j], pin, .03))
  list(B = B, n1 = n1, n2 = n2)
}
mk_het <- function(seed, p) {
  set.seed(seed * 100)
  n1 <- sample(20:40, 1); n2 <- sample(25:50, 1)
  a <- rgamma(n1, 2) / 2; b <- rgamma(n2, 2) / 2
  B <- matrix(0, n1, n2)
  for (i in 1:n1) for (j in 1:n2) B[i,j] <- rbinom(1, 1, min(.9, p * a[i] * b[j]))
  list(B = B, n1 = n1, n2 = n2)
}
nets <- list(bA = mk_block(1, .6), bB = mk_block(4, .6), bC = mk_het(2, .08), bD = mk_het(5, .2),
             bE = mk_block(9, .6), bF = mk_het(3, .2))
to_nw <- function(z) {
  nn <- z$n1 + z$n2; M <- matrix(0, nn, nn); M[1:z$n1, z$n1 + 1:z$n2] <- z$B
  network(M, directed = FALSE, bipartite = z$n1)
}
terms <- list(gwb1degree = "bgwdegreefree1", gwb2degree = "bgwdegreefree2", gwb1dsp = "bgwdspfree1", gwb2dsp = "bgwdspfree2")
fmt <- function(v) paste(formatC(v, digits = 15, format = "g"), collapse = " ")

res <- list()
for (nm in names(nets)) {
  z <- nets[[nm]]; nw <- to_nw(z)
  for (tm in names(terms)) {
    f <- as.formula(paste("nw ~ edges +", tm))
    r <- try(suppressWarnings(suppressMessages(ergm(f, estimate = "MPLE"))), silent = TRUE)
    if (inherits(r, "try-error")) next
    co <- coef(r); se <- sqrt(diag(vcov(r)))
    if (!all(is.finite(se)) || any(se > 5) || co[3] < 0.05 || co[3] > 8) next
    mc <- NULL
    if (nm %in% c("bC", "bF")) {
      m <- try(suppressWarnings(suppressMessages(ergm(f, control = control.ergm(seed = 5, MCMC.samplesize = 20000, MCMC.interval = 500, MCMC.burnin = 50000)))), silent = TRUE)
      if (!inherits(m, "try-error") && coef(m)[3] > 0.1 && all(is.finite(sqrt(diag(vcov(m)))))) mc <- list(co = coef(m), se = sqrt(diag(vcov(m))))
    }
    cat(sprintf("%-4s %-11s MPLE %s%s\n", nm, tm, paste(round(co, 4), collapse = " "), if (is.null(mc)) "" else paste("  MCMLE", paste(round(mc$co, 4), collapse = " "))))
    res[[length(res) + 1]] <- list(net = nm, term = tm, co = co, se = se, mc = mc)
  }
}

out <- character()
w <- function(...) out <<- c(out, sprintf(...))
w("cscript")
w("")
w("capture adopath ++ \".\"")
w("capture adopath ++ \"lib\"")
w("* The core package nwcommands is found through the environment variable NWCORE (path of the core checkout).")
w("local nwcore : env NWCORE")
w("if `\"`nwcore'\"' == \"\" {")
w("	di as error \"set the environment variable NWCORE to the directory of the nwcommands (core) package\"")
w("	exit 198")
w("}")
w("adopath ++ `\"`nwcore'\"'")
w("adopath ++ `\"`c(pwd)'\"'")
w("quietly do `\"`nwcore'/unw_core.do\"'")
w("do unw_ergm.do")
w("capture adopath ++ \"lib/plugins/macos\"")
w("capture adopath ++ \"lib/plugins/unix\"")
w("capture adopath ++ \"lib/plugins/windows\"")
w("")
w("* Certifies the curved (estimated decay) two-mode terms gwb1degree, gwb2degree, gwb1dsp, gwb2dsp against R ergm 4.12.0:")
w("*  (1) MPLE coefficients (edges, weight, decay) and standard errors equal ergm(estimate = \"MPLE\"),")
w("*  (2) the MCMLE coefficients are within Monte Carlo noise of R's for two seeds.")
w("* Reference values: dev/gen_test_bipcurved.R (this file is generated by it).")
w("")
w("capture program drop bc_net")
w("program bc_net")
w("	// bc_net name n1 n2 \"person event person event ...\"")
w("	args name n1 n2 edges")
w("	nwclear")
w("	matrix __A = J(`n2', `n1', 0)")
w("	local k : word count `edges'")
w("	forvalues t = 1(2)`k' {")
w("		local i : word `t' of `edges'")
w("		local j : word `=`t'+1' of `edges'")
w("		matrix __A[`j', `i'] = 1")
w("	}")
w("	nwset, mat(__A) bipartite name(`name') nooutput")
w("	clear")
w("	set obs `=`n1'+`n2''")
w("end")
w("")
w("capture program drop bc_mple")
w("program bc_mple")
w("	// bc_mple net option \"coefs\" \"ses\"")
w("	args net opt coefs ses")
w("	qui nwergm `net', edges `opt'(0.5) method(mple)")
w("	tempname b V")
w("	matrix `b' = e(b)")
w("	matrix `V' = e(V)")
w("	local dmax 0")
w("	forvalues j = 1/3 {")
w("		local e : word `j' of `coefs'")
w("		local s : word `j' of `ses'")
w("		local d1 = abs(`b'[1,`j'] - `e')")
w("		local d2 = abs(sqrt(`V'[`j',`j']) - `s')")
w("		if `d1' > 1e-3 * max(1, abs(`e')) | `d2' > 1e-3 * max(1, `s') {")
w("			di as err \"FAIL MPLE `net' `opt': coefficient `j' is \" `b'[1,`j'] \" (R `e'), se \" sqrt(`V'[`j',`j']) \" (R `s')\"")
w("			exit 9")
w("		}")
w("		local dmax = max(`dmax', `d1', `d2')")
w("	}")
w("	di \"PASS `net' `opt': MPLE max difference to R \" %%9.2e `dmax'")
w("end")
w("")
w("capture program drop bc_mcmle")
w("program bc_mcmle")
w("	args net opt coefs ses")
w("	foreach sd in 101 202 {")
w("		set seed `sd'")
w("		qui nwergm `net', edges `opt'(0.5) method(mcmle) mcmcsamplesize(2000) mcmcinterval(100) mcmcburnin(5000) mcmleiterations(25) nologlik")
w("		tempname b")
w("		matrix `b' = e(b)")
w("		forvalues j = 1/3 {")
w("			local e : word `j' of `coefs'")
w("			local s : word `j' of `ses'")
w("			if abs(`b'[1,`j'] - `e') > 3.5 * `s' {")
w("				di as err \"FAIL MCMLE `net' `opt' seed `sd': coefficient `j' is \" `b'[1,`j'] \" but R gives `e' (se `s')\"")
w("				exit 9")
w("			}")
w("		}")
w("	}")
w("	di \"PASS `net' `opt': MCMLE within Monte Carlo noise of R for two seeds\"")
w("end")
w("")
for (nm in names(nets)) {
  rs <- Filter(function(r) r$net == nm, res)
  if (!length(rs)) next
  z <- nets[[nm]]
  e <- which(z$B == 1, arr.ind = TRUE)
  w("bc_net %s %d %d `\"%s\"'", nm, z$n1, z$n2, paste(as.vector(t(e)), collapse = " "))
  for (r in rs) {
    w("bc_mple %s %s `\"%s\"' `\"%s\"'", nm, terms[[r$term]], fmt(r$co), fmt(r$se))
    if (!is.null(r$mc)) w("bc_mcmle %s %s `\"%s\"' `\"%s\"'", nm, terms[[r$term]], fmt(r$mc$co), fmt(r$mc$se))
  }
  w("")
}
w("di \"test_nwergm_bipcurved: ALL OK\"")
writeLines(out, "cscripts/test_nwergm_bipcurved.do")
cat("wrote cscripts/test_nwergm_bipcurved.do\n")
